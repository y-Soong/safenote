-- 적용 환경: MySQL 8.0.42
-- 출처: .claude/requests/web_requests/prafta-054-plan.md §054-1 (사용자 확정 §4 a~d)
--
-- ★★★ 적용 순서 안내 (중요) ★★★
--   본 운영 환경에서는 prafta-054-1-near-miss-link-ddl.sql(SRC_* 컬럼 DROP + 연계테이블 CREATE)이
--   이미 적용되었다. 따라서 SRC_* 컬럼이 더 이상 존재하지 않으므로, 아래 (b)는
--   원래의 `WHERE SRC_ASSESSMENT_CD IS NOT NULL` 대신 전환 아차사고 ID를 직접 지정해 삭제한다.
--   (전환 아차사고 3건 = tb_near_miss 전체 = NM20260608001/NM20260608002/NM20260609001, MCP 확인)
--
-- ⚠️ MySQL Workbench safe update mode(Error 1175) 회피:
--   (a) UPDATE 의 WHERE 가 키 컬럼(ASSESSMENT_STATUS는 비키)이 아니므로 safe mode 에서 차단된다.
--   본 스크립트는 세션 한정으로 SQL_SAFE_UPDATES 를 끄고 끝에서 복구한다.
--
-- 내용(사용자 확정 §4 a~d):
--   (a) 전환으로 ASSESSMENT_STATUS='005' 가 된 위험성평가 건을 '001'(검토요청)로 복원
--   (b) 전환으로 생성된 아차사고 헤더 행 삭제(ID 직접 지정)
--   (c) SYS011 의 '005'(아차사고로 이관) 코드값 삭제 — (a) 로 005 평가건 0건 보장 후 안전
--
-- ⚠️ 첨부파일 보존 (매우 중요 — tb_file_info 를 절대 건드리지 말 것):
--   전환 시(040-5) 아차사고 FILE_MGMT_CD 에 원 평가건의 사진 관리코드를 *복사*해 넣었다.
--   MCP 확인 결과: NM20260609001 의 FILE_MGMT_CD = '002-20260608-00026' 이며 이는
--   살아남는 평가건 260600012 의 INIT_FILE_MGMT_CD 와 동일(공유)하다.
--   (나머지 2건 NM20260608001/NM20260608002 는 FILE_MGMT_CD = NULL)
--   ⇒ tb_file_info 행을 지우면 평가건 사진이 깨진다. 따라서 본 정리는 tb_near_miss 헤더
--      행만 DELETE 하고 tb_file_info 는 절대 삭제하지 않는다.
--   tb_near_miss 는 자식 테이블/물리 FK 가 없는 단일 헤더 테이블이므로 헤더 DELETE 만으로 정합.
--
-- 멱등성: 본 DML 은 1회성 정리다(재실행 시 (a)/(b) 대상이 0건이면 무영향, (c) 는 이미 삭제됨).
--         운영 적용 후 보관용.
-- ============================================================================

SET SQL_SAFE_UPDATES = 0;

-- ----------------------------------------------------------------------------
-- (a) 005 → 001 복원 (예상 2건: 평가코드 260600012, 260600013)
--     전환으로 '005(아차사고로 이관)' 상태가 된 위험성평가를 검토요청(001)로 되돌린다.
-- ----------------------------------------------------------------------------
UPDATE `tb_risk_assessment`
   SET `ASSESSMENT_STATUS` = '001'
     , `UPDATE_NO`         = 'SYSTEM'
     , `UPDATE_DATE`       = NOW()
 WHERE `ASSESSMENT_STATUS` = '005';

-- ----------------------------------------------------------------------------
-- (b) 전환 생성 아차사고 헤더 삭제 (3건, ID 직접 지정)
--     SRC_* 컬럼이 054-1로 이미 DROP 되어 조건으로 쓸 수 없으므로 ID 를 직접 나열한다.
--     ⚠️ tb_near_miss 헤더 행만 DELETE. tb_file_info 는 위 주석 근거로 미터치.
-- ----------------------------------------------------------------------------
DELETE FROM `tb_near_miss`
 WHERE `NEAR_MISS_ID` IN ('NM20260608001', 'NM20260608002', 'NM20260609001');

-- ----------------------------------------------------------------------------
-- (c) SYS011 '005'(아차사고로 이관) 코드값 삭제
--     (a) 로 005 평가건이 0건이 된 뒤 삭제해야 라벨 해석 누수가 없다(순서 보장됨).
-- ----------------------------------------------------------------------------
DELETE FROM `tb_syst_val_d`
 WHERE `SYST_VAL_CD`   = 'SYS011'
   AND `SYST_VAL_D_CD` = '005';

SET SQL_SAFE_UPDATES = 1;

