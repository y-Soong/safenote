-- PRAFTA — 아차사고 사건유형(SYS061)에서 '유해·위험요인 발견'(300) 제거
-- 작성일: 2026-06-10
-- 적용 환경: MySQL 8.0.42
--
-- 배경:
--   아차사고 보고 유형 SYS061 의 '300 유해·위험요인발견' 항목은 위험성평가(risk)
--   도메인과 기능이 중복된다. 위험성평가에서 별도로 관리하므로 아차사고 보고에서는
--   제거한다(앱 보고 폼 라디오 + 웹 사건관리 필터 드롭다운에서 동적으로 사라짐).
--
-- 영향 범위:
--   · 앱 보고 폼(NearMissReport.vue) : 정적 fallback 옵션 제거(코드 반영 완료) + 동적 목록 제거
--   · 웹 사건관리(NearMiss_01.vue)    : SYS061 동적 드롭다운에서 자동 제외
--   · 웹/앱 상세(NearMissInfo/Detail) : 유형명(incidentTypeNm)을 동적 조회 → 자동 정합
--   · 백엔드                          : 사건유형 allow-list 없음(통과값 그대로 저장) → 코드 변경 불필요
--
-- 데이터 안전성(적용 전 확인됨):
--   SELECT COUNT(*) FROM tb_near_miss WHERE INCIDENT_TYPE_CD = '300';  -- 0건(참조 없음)
--   → 실데이터가 0건이므로 코드 DELETE 안전. 만약 0이 아니면 DELETE 전 데이터 재분류 필요.
--
-- 멱등성: 이미 제거된 환경이면 DELETE 0건(에러 아님). 재실행 무해.
-- ============================================================================

-- (1) SYS061 사건유형 상세코드 '300' 제거
DELETE FROM `tb_syst_val_d`
 WHERE `SYST_VAL_CD` = 'SYS061'
   AND `SYST_VAL_D_CD` = '300';

-- (2) tb_near_miss.INCIDENT_TYPE_CD 컬럼 코멘트 정합(300 제거 반영)
ALTER TABLE `tb_near_miss`
  MODIFY COLUMN `INCIDENT_TYPE_CD` varchar(10) NOT NULL
  COMMENT '사건유형[SYS061] 100:아차사고 200:경미사고';

