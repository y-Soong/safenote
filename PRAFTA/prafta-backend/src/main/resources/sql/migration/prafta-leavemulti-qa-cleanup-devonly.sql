-- 작성일 : 2026-08-14 (재검증분 포함 / 컬레이션 오류 수정)
-- 대상   : 2026-08-14 QA 중 SOON(20260400013) 계정으로 생성된 연차 신청 9건
--
-- 생성 내역 (REQ_REASON 이 'QA ' 로 시작)
--   2026081400194  20260914  단일일(기준선 R1)          GROUP=NULL           승인('02')
--   2026081400195  20260915  기간 1일(E10)              LG2026081400001      대기('01')
--   2026081400196  20260917  기간 5일(N5/N11)           LG2026081400002      승인
--   2026081400197  20260918   〃                        LG2026081400002      승인
--   2026081400198  20260919   〃(토)                    LG2026081400002      승인
--   2026081400199  20260920   〃(일)                    LG2026081400002      승인
--   2026081400200  20260921   〃                        LG2026081400002      승인
--   2026081400201  20260923  기간 2일(결과알림 재검증)   LG2026081400003      승인
--   2026081400202  20260924   〃                        LG2026081400003      승인
--
-- ★ 'RQQDM121'(QA 시드 W8 미결 시간차)은 기존 시드 데이터다 — 삭제 대상이 아니다.
-- ★ 삭제 순서 중요: 사용실적 → 결재라인 → 요청 → 알림 → 부여 USED_DAYS 재계산.
--   마지막 재계산을 빼면 잔여가 줄어든 채로 남는다.
--
-- ※ 종전판의 `SET @QA_REQS` + FIND_IN_SET 방식은 ERROR 1267 (Illegal mix of collations)
--   을 낸다 — 사용자 변수는 접속 기본 컬레이션(utf8mb4_0900_ai_ci)이라 컬럼
--   (utf8mb4_unicode_ci)과 직접 비교할 수 없다. IN (리터럴) 로 대체했다.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- STEP 0. 삭제 전 확인 (9행이어야 정상)
-- -------------------------------------------------------------------------------------
SELECT R.REQ_ID, R.WORK_YMD, R.REQ_STATUS, R.LEAVE_GROUP_ID, R.REQ_REASON
     , L.LEAVE_ID, L.GRANT_ID, L.LEAVE_DAYS
  FROM TB_USER_ATTD_REQ R
  LEFT JOIN TB_USER_LEAVE_USE L
         ON L.CMPNY_CD = R.CMPNY_CD AND L.REQ_ID = R.REQ_ID
 WHERE R.CMPNY_CD = '001'
   AND R.REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                   ,'2026081400197','2026081400198','2026081400199'
                   ,'2026081400200','2026081400201','2026081400202')
 ORDER BY R.REQ_ID;

-- 정리 전 잔여 스냅샷 (복구 확인용)
SELECT LEAVE_CD, ROUND(SUM(GRANT_DAYS - USED_DAYS), 5) AS REMAIN
  FROM TB_USER_LEAVE_GRANT
 WHERE CMPNY_CD = '001' AND USER_CD = '20260400013'
   AND DEL_YN = 'N' AND STATUS = 'ACTIVE'
 GROUP BY LEAVE_CD;


-- -------------------------------------------------------------------------------------
-- STEP 1. 연차 사용실적 삭제 (기대: 9행)
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_LEAVE_USE
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199'
                 ,'2026081400200','2026081400201','2026081400202');

-- -------------------------------------------------------------------------------------
-- STEP 2. 결재라인 삭제
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_ATTD_REQ_APPROVAL
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199'
                 ,'2026081400200','2026081400201','2026081400202');

-- -------------------------------------------------------------------------------------
-- STEP 3. 요청 삭제 (기대: 9행)
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_ATTD_REQ
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199'
                 ,'2026081400200','2026081400201','2026081400202');

-- -------------------------------------------------------------------------------------
-- STEP 4. 알림 outbox 삭제 (QA 로 적재된 것만)
--   차례도래: LV_TURN_2026081400194_1 / LV_TURN_GRP_LG20260814000%
--   결과통보: LV_RESULT_20260814001%_APPROVED / LV_RESULT_GRP_LG20260814000%
-- -------------------------------------------------------------------------------------
DELETE FROM TB_NOTI_OUTBOX
 WHERE CMPNY_CD = '001'
   AND (   DEDUP_KEY LIKE 'LV_TURN_GRP_LG20260814000%'
        OR DEDUP_KEY LIKE 'LV_RESULT_GRP_LG20260814000%'
        OR DEDUP_KEY LIKE 'LV_TURN_20260814001%'
        OR DEDUP_KEY LIKE 'LV_RESULT_20260814001%' );

-- -------------------------------------------------------------------------------------
-- STEP 5. ★부여 USED_DAYS 재계산 — 이 단계를 빼면 잔여가 줄어든 채로 남는다.
--   남은 CONFIRMED 사용실적 합으로 되돌린다(운영 recomputeGrantUsedDays 와 동일 식).
--   ※ Workbench Safe Updates 로 막히면 세션에서만 SET SQL_SAFE_UPDATES=0; 후 실행하고 되돌릴 것.
-- -------------------------------------------------------------------------------------
UPDATE TB_USER_LEAVE_GRANT G
   SET G.USED_DAYS = IFNULL((
           SELECT SUM(U.LEAVE_DAYS)
             FROM TB_USER_LEAVE_USE U
            WHERE U.CMPNY_CD     = G.CMPNY_CD
              AND U.GRANT_ID     = G.GRANT_ID
              AND U.LEAVE_STATUS = 'CONFIRMED'
              AND U.DEL_YN       = 'N'
       ), 0)
 WHERE G.CMPNY_CD = '001'
   AND G.USER_CD  = '20260400013';


