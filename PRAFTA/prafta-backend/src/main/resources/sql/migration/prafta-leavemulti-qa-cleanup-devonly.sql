-- 작성일 : 2026-08-14
-- 대상   : 2026-08-14 QA 중 SOON(20260400013) 계정으로 생성된 연차 신청 7건
--
-- 생성 내역
--   R1  단일일   : REQ 2026081400194 (20260914, LEAVE_GROUP_ID=NULL)
--   E10 기간1일  : REQ 2026081400195 (20260915, LG2026081400001)
--   N5/N11 기간5일: REQ 2026081400196~200 (20260917~21, LG2026081400002)
--
-- ★ 삭제 순서가 중요하다: 사용실적 → 결재라인 → 요청 → 알림 → 부여 USED_DAYS 재계산.
--   부여 USED_DAYS 를 되돌리지 않으면 잔여가 줄어든 채로 남는다.
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- STEP 0. 삭제 전 확인 (7행이어야 정상)
-- -------------------------------------------------------------------------------------
SELECT R.REQ_ID, R.WORK_YMD, R.LEAVE_GROUP_ID, R.REQ_STATUS, R.REQ_REASON
     , L.LEAVE_ID, L.GRANT_ID, L.LEAVE_DAYS
  FROM TB_USER_ATTD_REQ R
  LEFT JOIN TB_USER_LEAVE_USE L
         ON L.CMPNY_CD = R.CMPNY_CD AND L.REQ_ID = R.REQ_ID
 WHERE R.CMPNY_CD = '001'
   AND R.REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                   ,'2026081400197','2026081400198','2026081400199','2026081400200')
 ORDER BY R.REQ_ID;

-- 영향받은 부여(복구 확인용 스냅샷)
SELECT GRANT_ID, GRANT_DAYS, USED_DAYS, ROUND(GRANT_DAYS-USED_DAYS,5) AS REMAIN
  FROM TB_USER_LEAVE_GRANT
 WHERE CMPNY_CD='001' AND USER_CD='20260400013'
   AND GRANT_ID IN ('G2026052600239','G2026052600231','G2026052600233'
                   ,'G2026052600234','G2026052600235','G2026052600236');


-- -------------------------------------------------------------------------------------
-- STEP 1. 연차 사용실적 삭제
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_LEAVE_USE
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199','2026081400200');
-- 기대: 7행

-- -------------------------------------------------------------------------------------
-- STEP 2. 결재라인 삭제
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_ATTD_REQ_APPROVAL
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199','2026081400200');

-- -------------------------------------------------------------------------------------
-- STEP 3. 요청 삭제
-- -------------------------------------------------------------------------------------
DELETE FROM TB_USER_ATTD_REQ
 WHERE CMPNY_CD = '001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199','2026081400200');
-- 기대: 7행

-- -------------------------------------------------------------------------------------
-- STEP 4. 알림 outbox 삭제 (QA 로 적재된 것만)
-- -------------------------------------------------------------------------------------
DELETE FROM TB_NOTI_OUTBOX
 WHERE CMPNY_CD = '001'
   AND ( DEDUP_KEY IN ('LV_TURN_2026081400194_1')
      OR DEDUP_KEY LIKE 'LV_TURN_GRP_LG20260814%' );

-- -------------------------------------------------------------------------------------
-- STEP 5. ★부여 USED_DAYS 재계산 (남은 CONFIRMED 사용실적 합으로 되돌린다)
--         이 단계를 빼면 잔여가 줄어든 채로 남는다.
-- -------------------------------------------------------------------------------------
UPDATE TB_USER_LEAVE_GRANT G
   SET G.USED_DAYS = IFNULL((
           SELECT SUM(U.LEAVE_DAYS)
             FROM TB_USER_LEAVE_USE U
            WHERE U.CMPNY_CD     = G.CMPNY_CD
              AND U.GRANT_ID     = G.GRANT_ID
              AND U.LEAVE_STATUS = 'CONFIRMED'
              AND U.DEL_YN       = 'N'
       ), 0)
 WHERE G.CMPNY_CD = '001'
   AND G.USER_CD  = '20260400013';
-- ※ Workbench Safe Updates 로 막히면 세션에서만 SET SQL_SAFE_UPDATES=0; 후 실행하고 되돌릴 것.


-- -------------------------------------------------------------------------------------
-- STEP 6. 정리 확인
-- -------------------------------------------------------------------------------------
SELECT COUNT(*) AS LEFT_REQ
  FROM TB_USER_ATTD_REQ
 WHERE CMPNY_CD='001'
   AND REQ_ID IN ('2026081400194','2026081400195','2026081400196'
                 ,'2026081400197','2026081400198','2026081400199','2026081400200');
-- 기대: 0

SELECT LEAVE_CD, ROUND(SUM(GRANT_DAYS-USED_DAYS),5) AS REMAIN
  FROM TB_USER_LEAVE_GRANT
 WHERE CMPNY_CD='001' AND USER_CD='20260400013' AND DEL_YN='N' AND STATUS='ACTIVE'
 GROUP BY LEAVE_CD;
-- 기대: SYS_ANNUAL 5.64286 / SYS_MONTHLY 8.87500 (QA 이전 값으로 복귀)
